"""Build Claude Code subagent files from The Agency's role cards.

The role cards stay the source; agents.json picks the ones worth calling directly and pins each one's model and tools.
Each built file carries a marker line, and this script writes, replaces or removes only files that carry it, so a
hand-written agent with the same name is never touched. Relative links in a card become absolute paths to this skill.

Default: print the plan and change nothing. --check exits 1 when any file is missing, stale or orphaned. --apply
writes the plan. Exit 2 on a bad agents.json, a missing role card, or a clash with a file this script did not write.
"""
import argparse
import json
import re
import sys
from pathlib import Path

SKILL = Path(__file__).resolve().parents[1]
CONFIG = SKILL / "agents.json"
MARKER = "Generated by build_agents.py"
MODELS = {"haiku", "sonnet", "opus", "inherit"}
NAME = re.compile(r"^[a-z][a-z0-9-]{2,63}$")
LINK = re.compile(r"\]\((?!https?:|#|[A-Za-z]:[\\/]|/)([^)\s#]+)(#[^)\s]*)?\)")


class BuildError(Exception):
    """agents.json is wrong, a role card is missing, or a target file is not ours: exit 2."""


def split_card(text):
    """Return (frontmatter dict, body) for a role card with name/description frontmatter."""
    text = text.replace("\r\n", "\n")
    if not text.startswith("---\n") or "\n---\n" not in text[4:]:
        raise BuildError("role card has no frontmatter")
    head, body = text[4:].split("\n---\n", 1)
    meta = {}
    for line in head.splitlines():
        key, _, value = line.partition(":")
        if value:
            meta[key.strip()] = value.strip()
    if not meta.get("description"):
        raise BuildError("role card frontmatter has no description")
    return meta, body.lstrip("\n")


def absolute_links(body, card):
    def fix(match):
        target = (card.parent / match.group(1)).resolve()
        return f"]({target.as_posix()}{match.group(2) or ''})"
    return LINK.sub(fix, body)


def render(agent, skill=SKILL):
    card = (skill / agent["role"]).resolve()
    if not card.is_file():
        raise BuildError(f"{agent['name']}: role card missing: {card}")
    meta, body = split_card(card.read_text(encoding="utf-8"))
    description = meta["description"].replace('"', "'")
    lines = ["---", f"name: {agent['name']}", f'description: "{description}"',
             f"tools: {', '.join(agent['tools'])}", f"model: {agent['model']}", "---", "",
             f"<!-- {MARKER} from {card.as_posix()}. Edit the role card, then rebuild; edits here are overwritten. -->",
             "",
             f"You are The Agency's {meta.get('name', agent['name'])} role, called directly as a subagent. The role card "
             "below is your full brief. The parent's message supplies the Inputs it lists; if one is missing, say which "
             "and stop rather than guess. Return once, as its Output and Return sections say.", "",
             absolute_links(body, card).rstrip(), ""]
    return "\n".join(lines)


def load(config=CONFIG):
    try:
        data = json.loads(Path(config).read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise BuildError(f"cannot read {config}: {error}") from error
    agents, seen = data.get("agents"), set()
    if not isinstance(agents, list) or not agents:
        raise BuildError("agents.json needs a non-empty agents list")
    for agent in agents:
        name = agent.get("name", "")
        if not NAME.match(name) or name in seen:
            raise BuildError(f"bad or repeated agent name: {name!r}")
        seen.add(name)
        if agent.get("model") not in MODELS:
            raise BuildError(f"{name}: model must be one of {sorted(MODELS)}")
        if not agent.get("role") or not isinstance(agent.get("tools"), list) or not agent["tools"]:
            raise BuildError(f"{name}: needs a role path and a non-empty tools list")
        if not agent.get("why"):
            raise BuildError(f"{name}: say why it is worth calling directly")
    return agents


def ours(path):
    try:
        return MARKER in Path(path).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False


def plan(target, agents, skill=SKILL):
    """List of (action, path, text) where action is create, update, same or remove."""
    target = Path(target)
    steps, wanted = [], set()
    for agent in agents:
        path = target / f"{agent['name']}.md"
        wanted.add(path.name)
        text = render(agent, skill)
        if not path.exists():
            steps.append(("create", path, text))
        elif not ours(path):
            raise BuildError(f"{path} exists and was not written by this script; rename the agent or move that file")
        elif path.read_text(encoding="utf-8") != text:
            steps.append(("update", path, text))
        else:
            steps.append(("same", path, text))
    if target.is_dir():
        for path in sorted(target.glob("*.md")):
            if path.name not in wanted and ours(path):
                steps.append(("remove", path, None))
    return steps


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--target", default=str(Path.home() / ".claude" / "agents"), help="Claude Code agents folder")
    parser.add_argument("--config", default=str(CONFIG))
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--apply", action="store_true")
    args = parser.parse_args(argv)
    try:
        steps = plan(args.target, load(args.config))
    except BuildError as error:
        print(f"ERROR {error}", file=sys.stderr)
        return 2
    for action, path, _ in steps:
        print(f"{action:7} {path}")
    changes = [s for s in steps if s[0] != "same"]
    if args.apply:
        Path(args.target).mkdir(parents=True, exist_ok=True)
        for action, path, text in changes:
            if action == "remove":
                path.unlink()
            else:
                path.write_text(text, encoding="utf-8", newline="\n")
        print(f"applied {len(changes)} change(s)")
        return 0
    if args.check:
        print("OK" if not changes else f"STALE: {len(changes)} change(s); run with --apply")
        return 1 if changes else 0
    print(f"{len(changes)} change(s) planned; nothing written. Run with --apply to write them.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
